using System.Globalization;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Fish.Xenobiology;
using Content.Shared.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Fish.Xenobiology;

/// <summary>Displays colony measurements and the complete mutation and extract reference.</summary>
[GenerateTypedNameReferences]
public sealed partial class FishXenobiologyWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private ILocalizationManager _loc = default!;
    private readonly List<RichTextLabel> _specimenRows = new();
    private readonly List<FishXenobiologyBreedPrototype> _breeds;
    private string? _selectedBreed;

    public event Action? ProcessRequested;
    public event Action? EjectRequested;

    public FishXenobiologyWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _breeds = _prototype.EnumeratePrototypes<FishXenobiologyBreedPrototype>()
            .OrderBy(breed => breed.Tier).ThenBy(breed => _loc.GetString(breed.Name)).ToList();
        ProcessButton.OnPressed += _ => ProcessRequested?.Invoke();
        EjectButton.OnPressed += _ => EjectRequested?.Invoke();
        SpecimensButton.OnPressed += _ => ShowCatalog(false);
        CatalogButton.OnPressed += _ => ShowCatalog(true);
        Search.OnTextChanged += _ => PopulateBreeds();
        PopulateBreeds();
        if (_breeds.Count > 0)
            SelectBreed(_breeds[0]);
    }

    private void ShowCatalog(bool show)
    {
        CatalogContent.Visible = show;
        SpecimenScroll.Visible = !show;
        CatalogButton.Pressed = show;
        SpecimensButton.Pressed = !show;
    }

    /// <summary>Updates measurements in existing controls without recreating the scroll content every second.</summary>
    public void UpdateState(FishXenobiologyBoundUserInterfaceState state)
    {
        Status.Text = _loc.GetString(!state.Powered ? "fish-xeno-unpowered" : "fish-xeno-count",
            ("count", state.Specimens.Count));
        ProcessorControls.Visible = state.Processor;
        ProcessButton.Disabled = !state.CanProcess;
        EjectButton.Disabled = !state.HasInput;
        Progress.Value = state.Progress;

        for (var i = _specimenRows.Count; i < state.Specimens.Count; i++)
        {
            var row = new RichTextLabel { HorizontalExpand = true, Margin = new Thickness(10) };
            var panel = new PanelContainer { HorizontalExpand = true };
            panel.AddChild(row);
            SpecimenList.AddChild(panel);
            _specimenRows.Add(row);
        }
        for (var i = 0; i < _specimenRows.Count; i++)
        {
            var row = _specimenRows[i];
            row.Parent!.Visible = i < state.Specimens.Count;
            if (i >= state.Specimens.Count)
                continue;

            var slime = state.Specimens[i];
            if (!_prototype.TryIndex<FishXenobiologyBreedPrototype>(slime.Breed, out var breed))
                continue;
            var stage = _loc.GetString(slime.Dead ? "fish-xeno-dead" : slime.Adult ? "fish-xeno-adult" : "fish-xeno-baby");
            row.SetMessage(_loc.GetString("fish-xeno-specimen",
                ("breed", _loc.GetString(breed.Name)), ("stage", stage), ("generation", slime.Generation),
                ("growth", MathF.Round(slime.Growth * 100)), ("biomass", MathF.Round(slime.Biomass)),
                ("hunger", MathF.Round(slime.Hunger)),
                ("temperature", Format(slime.Temperature - 273.15f)),
                ("mutation", MathF.Round(slime.MutationChance * 100)), ("offspring", slime.Offspring),
                ("yield", slime.ExtractYield), ("rate", Format(slime.GrowthRate)),
                ("docility", MathF.Round(slime.Docility * 100)), ("tolerance", Format(slime.ThermalTolerance))));
        }
    }

    private void PopulateBreeds()
    {
        BreedList.RemoveAllChildren();
        foreach (var breed in _breeds)
        {
            var name = _loc.GetString(breed.Name);
            if (!name.Contains(Search.Text, StringComparison.CurrentCultureIgnoreCase))
                continue;
            var button = new Button
            {
                Text = _loc.GetString("fish-xeno-breed-button", ("tier", breed.Tier), ("name", name)),
                ToggleMode = true,
                Pressed = _selectedBreed == breed.ID,
                HorizontalExpand = true,
            };
            button.OnPressed += _ => SelectBreed(breed);
            BreedList.AddChild(button);
        }
    }

    private void SelectBreed(FishXenobiologyBreedPrototype breed)
    {
        _selectedBreed = breed.ID;
        PopulateBreeds();
        BreedDetails.RemoveAllChildren();
        var icon = new EntityPrototypeView { SetSize = new System.Numerics.Vector2(96, 96) };
        icon.SetPrototype(_prototype.Index(breed.Mob));
        BreedDetails.AddChild(icon);
        BreedDetails.AddChild(new Label { Text = _loc.GetString(breed.Name), StyleClasses = { "LabelHeading" } });
        AddDetails(_loc.GetString(breed.Description));
        AddDetails(_loc.GetString("fish-xeno-breed-conditions",
            ("seconds", breed.GrowthDuration), ("growth", breed.GrowthBiomass), ("division", breed.DivisionBiomass),
            ("minimum", Format(breed.MinimumTemperature - 273.15f)),
            ("maximum", Format(breed.MaximumTemperature - 273.15f))));
        AddDetails(_loc.GetString("fish-xeno-mutations"));
        if (breed.Mutations.Count == 0)
            AddDetails(_loc.GetString("fish-xeno-stable-lineage"));
        foreach (var mutation in breed.Mutations)
        {
            var next = _prototype.Index(mutation.Key);
            var button = new Button { Text = _loc.GetString(next.Name), HorizontalExpand = true };
            button.OnPressed += _ => SelectBreed(next);
            BreedDetails.AddChild(button);
        }
        AddDetails(_loc.GetString("fish-xeno-reactions"));
        foreach (var reaction in _prototype.EnumeratePrototypes<FishXenobiologyReactionPrototype>()
                     .Where(reaction => reaction.Breed.Id == breed.ID))
        {
            var reagent = _prototype.Index<ReagentPrototype>(reaction.Reagent);
            AddDetails(_loc.GetString("fish-xeno-reaction",
                ("name", _loc.GetString(reaction.Name)), ("amount", reaction.Amount.ToString()),
                ("reagent", reagent.LocalizedName), ("description", _loc.GetString(reaction.Description))));
        }
    }

    private void AddDetails(string text)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(text);
        BreedDetails.AddChild(label);
    }

    private static string Format(float number) => number.ToString("0.0", CultureInfo.CurrentCulture);
}
