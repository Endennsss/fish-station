using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Fish.Storage;
using Content.Shared.Stacks;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Fish.Storage;

[GenerateTypedNameReferences]
public sealed partial class FishOreBagFilterWindow : FancyWindow
{
    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private ILocalizationManager _loc = default!;

    private readonly Dictionary<ProtoId<StackPrototype>, CheckBox> _stackButtons = new();

    public event Action<ProtoId<StackPrototype>, bool>? StackToggled;
    public event Action<bool>? AllToggled;
    public event Action<bool>? OtherToggled;

    public FishOreBagFilterWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SelectAllButton.OnPressed += _ => AllToggled?.Invoke(true);
        ClearAllButton.OnPressed += _ => AllToggled?.Invoke(false);
        OtherCheckBox.OnToggled += args => OtherToggled?.Invoke(args.Pressed);
    }

    public void LoadStackTypes(IReadOnlyCollection<StackPrototype> stackTypes)
    {
        _stackButtons.Clear();
        StackEntries.RemoveAllChildren();

        var sprite = _entity.System<SpriteSystem>();
        var entries = stackTypes
            .Select(prototype => (Prototype: prototype, Name: _loc.GetString(prototype.Name)))
            .OrderBy(entry => entry.Name, StringComparer.CurrentCulture)
            .ThenBy(entry => entry.Prototype.ID, StringComparer.Ordinal);

        foreach (var entry in entries)
        {
            ProtoId<StackPrototype> stackType = entry.Prototype.ID;
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 4,
            };

            if (entry.Prototype.Icon != null)
            {
                row.AddChild(new TextureRect
                {
                    Texture = sprite.Frame0(entry.Prototype.Icon),
                    Stretch = TextureRect.StretchMode.KeepCentered,
                    VerticalAlignment = VAlignment.Center,
                });
            }

            var checkBox = new CheckBox
            {
                Text = entry.Name,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            };
            checkBox.OnToggled += args => StackToggled?.Invoke(stackType, args.Pressed);
            row.AddChild(checkBox);
            StackEntries.AddChild(row);
            _stackButtons.Add(stackType, checkBox);
        }
    }

    public void UpdateState(FishOreBagFilterComponent filter)
    {
        foreach (var (stackType, checkBox) in _stackButtons)
        {
            checkBox.Pressed = !filter.DisabledStackTypes.Contains(stackType);
        }

        OtherCheckBox.Pressed = filter.CollectOther;
    }
}
